/*
 * Dicionario portugues -> ingles dos diagramas. A chave e a string portuguesa EXATA que o codigo
 * em diagramas.mjs desenha (uma linha de caixa e uma entrada: as quebras de linha sao decisao do
 * desenho, entao a traducao respeita a quebra).
 *
 * Regras (quem aplica e `traduzir`, em lib.mjs):
 *   1. Em 'en', toda string visivel precisa de traducao. Sem entrada, o gerador LANCA ERRO com a
 *      string. Nao existe queda silenciosa para portugues.
 *   2. Identificador ou nome proprio que fica igual: entrada com valor igual a chave
 *      (ex.: 'Claude Code': 'Claude Code'). E a forma explicita e auditavel.
 *   3. Excecao unica, para nao encher este arquivo de ruido: uma string de UMA palavra so, ASCII,
 *      que contem simbolo de codigo (. / _ @ * < > : = - { } " ' [ ] ( ) # + % & ou digito)
 *      passa sem traducao (nomes de executavel, hook, caminho, flag). Palavra simples sem simbolo
 *      ('Equipe', 'Modelos') nunca passa: exige entrada.
 *   4. Chips e linhas de caixa marcadas `mono` sao codigo (nomes lidos do disco, JSON, caminhos)
 *      e nao sao traduzidos.
 *   5. Strings com numero lido do disco ('8 hooks') entram por PADROES (regex -> funcao).
 *
 * Ressalva declarada: a esteira do banner e o exemplo JSON de varredura citam
 * `reports/seguranca.json`, um caminho literal de exemplo; fica como esta.
 */

